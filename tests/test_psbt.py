def test_split_key_enforces_minimal_type_encoding():
    from yubtc.psbt import _split_key
    # Single-byte type.
    assert _split_key(b'\x02\xaa\xbb') == (2, b'\xaa\xbb')
    # Non-minimal: `fd 02 00` encodes type 2 (the spec's example).
    with pytest.raises(NonMinimalCompactSize):
        _split_key(b'\xfd\x02\x00')
    # `fd 00 02` is type 512 -- minimal, fine.
    assert _split_key(b'\xfd\x00\x02')[0] == 512
    # Minimal 3-byte type (300 > 0xfc).
    assert _split_key(b'\xfd\x2c\x01') == (300, b'')
    # Non-minimal 5-byte type (0x0100 <= 0xffff).
    with pytest.raises(NonMinimalCompactSize):
        _split_key(b'\xfe\x00\x01\x00\x00')
    # Minimal 5-byte type (0x10000 > 0xffff).
    assert _split_key(b'\xfe\x00\x00\x01\x00')[0] == 0x1_0000
    # Non-minimal 9-byte type.
    with pytest.raises(NonMinimalCompactSize):
        _split_key(b'\xff\x00\x00\x01\x00\x00\x00\x00\x00')
    # Minimal 9-byte type.
    assert _split_key(b'\xff\x00\x00\x00\x00\x01\x00\x00\x00')[0] == 0x1_0000_0000
    # Truncated type prefixes.
    for bad in [b'', b'\xfd', b'\xfd\x01', b'\xfe\x01', b'\xff\x01']:
        with pytest.raises(Truncated):
            _split_key(bad)


