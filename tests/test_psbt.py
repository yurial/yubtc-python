    from yubtc.psbt import _encode_witness_stack
    stack = _encode_witness_stack([b'\x01']) + b'\x00'
    psbt.inputs[0].final_scriptwitness = stack
    with pytest.raises(IncompleteInput):
        extract_transaction(psbt=psbt)


