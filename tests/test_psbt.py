def replay(psbt, seed, passphrase, kdf):
    """create -> sign -> finalize -> extract; the four stage strings."""
    unsigned = to_base64(psbt=psbt)
    unsigned_list = sign_psbt(seed=seed, passphrase=passphrase, kdf=kdf,
                              psbt=psbt)
    assert unsigned_list == []
    signed = to_base64(psbt=psbt)
    finalize_psbt(psbt=psbt)
    finalized = to_base64(psbt=psbt)
    wire_hex = extract_transaction(psbt=psbt).serialize_wire().hex()
    return unsigned, signed, finalized, wire_hex


