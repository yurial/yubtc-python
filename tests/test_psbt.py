def fixture_key(nonce: int):
    """Offline derivation (yubtc cascade -- deterministic)."""
    return seed2privkey(seed=SEED, nonce=nonce, passphrase='', kdf='yubtc')


def spk(nonce: int, form: str, seed: str = SEED, passphrase: str = '',
        kdf: str = 'yubtc') -> bytes:
    """`scriptPubKey` of the `(nonce, form)` key under
    `(seed, passphrase, kdf)` (the fixture tuple by default)."""
    key = seed2privkey(seed=seed, nonce=nonce, passphrase=passphrase,
                       kdf=kdf, addr_type=form)
    pubkey = privkey2pubkey(privkey=key)
    if form == AddrType.LEGACY:
        return bytes(CScript([OP_DUP, OP_HASH160, hash160(pubkey),
                              OP_EQUALVERIFY, OP_CHECKSIG]))
    if form == AddrType.NATIVE:
        return bytes(make_p2wpkh_lock_script(hash160=hash160(pubkey)))
    return bytes(make_p2tr_lock_script(
        output_key=taproot_output_key(internal_xonly=pubkey[1:33])))


