def test_combine_refuses_foreign_transactions_and_conflicts():
    psbt, key = signed_pair_of_psbt()
    # Different unsigned tx.
    other_unsigned, other_inputs = three_forms_unsigned()
    other_unsigned = other_unsigned._replace(vout=(
        other_unsigned.vout[0]._replace(amount=999),))
    other = create_psbt(unsigned_tx=other_unsigned, inputs=other_inputs)
    with pytest.raises(ForeignTransaction):
        combine_psbt(psbt=psbt, other=other)
    # Same key, different signature value.
    a = from_base64(s=to_base64(psbt=psbt))
    b = from_base64(s=to_base64(psbt=psbt))
    assert sign_psbt_input(psbt=a, index=0, privkey=key)
    assert sign_psbt_input(psbt=b, index=0, privkey=key)
    sig = bytearray(b.inputs[0].partial_sigs[0][1])
    sig[10] ^= 0xff
    b.inputs[0].partial_sigs[0] = (b.inputs[0].partial_sigs[0][0], bytes(sig))
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=a, other=b)
    # Same for an unknown global pair.
    c = from_base64(s=to_base64(psbt=psbt))
    d = from_base64(s=to_base64(psbt=psbt))
    c.unknown_global.append(UnknownKv(key=b'\x51\x01', value=b'\x01'))
    d.unknown_global.append(UnknownKv(key=b'\x51\x01', value=b'\x02'))
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=c, other=d)
    # And a typed per-input field.
    e = from_base64(s=to_base64(psbt=psbt))
    f = from_base64(s=to_base64(psbt=psbt))
    e.inputs[0].redeem_script = b'\x01'
    f.inputs[0].redeem_script = b'\x02'
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=e, other=f)
    # And the witness_utxo.
    g = from_base64(s=to_base64(psbt=psbt))
    g.inputs[0].witness_utxo = g.inputs[0].witness_utxo._replace(amount=1)
    assert sign_psbt_input(psbt=a, index=0, privkey=key)
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=a, other=g)
    # And a final field.
    h = from_base64(s=to_base64(psbt=psbt))
    k = from_base64(s=to_base64(psbt=psbt))
    h.inputs[0].final_scriptsig = b'\x01'
    k.inputs[0].final_scriptsig = b'\x02'
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=h, other=k)


def test_combine_merges_disjoint_signers_and_unknowns():
    psbt, key_a = signed_pair_of_psbt()
    a = from_base64(s=to_base64(psbt=psbt))
    b = from_base64(s=to_base64(psbt=psbt))
    assert sign_psbt_input(psbt=a, index=0, privkey=key_a)
    # Signer B cannot sign (foreign key) -- emulate a disjoint signer
    # by injecting its synthetic partial sig directly.
    b.inputs[0].partial_sigs.append((b'\x02' * 33, b'\xbb' * 64))
    b.unknown_global.append(UnknownKv(key=b'\x51\x07', value=b'\x09'))
    ab = combine_psbt(psbt=a, other=b)
    ba = combine_psbt(psbt=b, other=a)
    assert serialize_psbt(psbt=ab) == serialize_psbt(psbt=ba), 'commutativity'
    # Owner sig + synthetic sig + unknown pair, all present once.
    assert len(ab.inputs[0].partial_sigs) == 2
    assert len(ab.unknown_global) == 1
    # combine(a, combine(a, b)) stays stable.
    aba = combine_psbt(psbt=a, other=ab)
    assert serialize_psbt(psbt=aba) == serialize_psbt(psbt=ab)


def test_combine_fills_one_sided_fields_and_detects_witness_conflicts():
    psbt, key = signed_pair_of_psbt()
    a = from_base64(s=to_base64(psbt=psbt))
    b = from_base64(s=to_base64(psbt=psbt))
    # a finalizes its input (final_scriptwitness present), b does not:
    # the (Some, None) arms of every merge run.
    assert sign_psbt_input(psbt=a, index=0, privkey=key)
    finalize_psbt_input(psbt=a, index=0)
    # A conflicting final_scriptwitness triggers that call's
    # ConflictingField arm.
    from yubtc.psbt import _encode_witness_stack
    b.inputs[0].final_scriptwitness = _encode_witness_stack([b'\x01'])
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=a, other=b)
    # Without the conflict the one-sided merge succeeds and keeps the
    # finalized side.
    b.inputs[0].final_scriptwitness = None
    merged = combine_psbt(psbt=a, other=b)
    assert merged.inputs[0].final_scriptwitness is not None
    # Non-witness UTXO and sighash_type conflicts (same arm shape).
    c = from_base64(s=to_base64(psbt=psbt))
    d = from_base64(s=to_base64(psbt=psbt))
    c.inputs[0].sighash_type = 1
    d.inputs[0].sighash_type = 3
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=c, other=d)
    e = from_base64(s=to_base64(psbt=psbt))
    f = from_base64(s=to_base64(psbt=psbt))
    e.inputs[0].witness_script = b'\x01'
    f.inputs[0].witness_script = b'\x02'
    with pytest.raises(ConflictingField):
        combine_psbt(psbt=e, other=f)


